"""LaTeX table for the E11 sensitivity analysis (reads e11_sensitivity.json)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
d = json.load(open(os.path.join(EXP, "results", "extra", "e11", "e11_sensitivity.json")))["results"]
NAMES = {"pickscore": "PickScore", "imagereward": "ImageReward", "laion_aes": "LAION-Aes",
         "hpsv21": "HPSv2.1"}


def f(r):
    lo, hi = r["ci_pct"]
    return f"${r['pct']:+.1f}$\\,{{\\scriptsize$[{lo:+.1f}, {hi:+.1f}]$}}"


L = ["% generated by experiments/extra/e11_sensitivity_table.py -- do not edit",
     r"\begin{tabular}{lcccc}", r"\toprule",
     r"Scorer & LOCO range & LOCO CI $<0$ & Dish cap 2 & Dish cap 3 \\", r"\midrule"]
for s, name in NAMES.items():
    loco = [v["dataset"] for k, v in d[s].items() if k.startswith("loco:")]
    pts = [r["pct"] for r in loco]
    neg = sum(r["ci_pct"][1] < 0 for r in loco)
    L.append(f"{name} & ${min(pts):+.1f}$ to ${max(pts):+.1f}$ & {neg}/{len(loco)} & "
             f"{f(d[s]['cap:2']['dataset'])} & {f(d[s]['cap:3']['dataset'])} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    EXP, "..", "paper_kbs", "figures", "tables", "tabA_e11sens.tex")
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(L))
