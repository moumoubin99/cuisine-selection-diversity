"""LaTeX tables for E15 (reads results/extra/e15/<reader>/e15.json)."""
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
R = {r: json.load(open(os.path.join(EXP, "results", "extra", "e15", r, "e15.json")))
     for r in ("qwen", "pixtral", "siglip")}
OUT = os.path.join(EXP, "..", "paper_kbs", "figures", "tables")
ROWS = [("generation_dpo_minus_sdxl", r"Diffusion-DPO vs SDXL, random-16"),
        ("selection_sdxl:pickscore", r"SDXL: PickScore top-16 vs random-16"),
        ("selection_dpo:pickscore", r"Diffusion-DPO: PickScore top-16 vs random-16"),
        ("both_dpo_top_minus_sdxl_rand:pickscore", r"DPO PickScore top-16 vs SDXL random-16"),
        ("selection_sdxl:imagereward", r"SDXL: ImageReward top-16 vs random-16"),
        ("selection_dpo:imagereward", r"Diffusion-DPO: ImageReward top-16 vs random-16"),
        ("both_dpo_top_minus_sdxl_rand:imagereward", r"DPO ImageReward top-16 vs SDXL random-16")]


def pct(d):
    f = lambda x: 100 * (np.exp(x) - 1)
    return f"${f(d['mean']):+.1f}$\\,{{\\scriptsize$[{f(d['ci'][0]):+.1f}, {f(d['ci'][1]):+.1f}]$}}"


def nat(d, dig):
    return (f"${d['mean']:+.{dig}f}$\\,{{\\scriptsize$[{d['ci'][0]:+.{dig}f}, "
            f"{d['ci'][1]:+.{dig}f}]$}}")


def rule(i):
    return [r"\midrule"] if i in (1, 4) else []


hdr = "% generated by experiments/extra/e15_table.py -- do not edit"
L = [hdr, r"\begin{tabular}{lcccc}", r"\toprule",
     r" & Label-free & \multicolumn{3}{c}{Dish-label Vendi (reader)} \\",
     r"\cmidrule(lr){3-5}",
     r"Contrast & DINOv2 & Qwen2.5-VL & Pixtral & SigLIP \\", r"\midrule"]
for i, (key, name) in enumerate(ROWS):
    L += rule(i)
    L.append(f"{name} & {pct(R['qwen']['emb'][key])} & "
             + " & ".join(pct(R[r]["lab"][key]) for r in ("qwen", "pixtral", "siglip")) + r" \\")
L += [r"\bottomrule", r"\end{tabular}"]
open(os.path.join(OUT, "tabA_e15div.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L))

J = [("pickscore", "PickScore$^\\dagger$", 3), ("imagereward", "ImageReward", 3),
     ("laion_aes", "LAION-Aes", 3), ("hpsv21", "HPSv2.1", 4)]
L = [hdr, r"\begin{tabular}{lcccc}", r"\toprule",
     "Contrast & " + " & ".join(n for _, n, _ in J) + r" \\", r"\midrule"]
q = R["qwen"]["score_native"]
for i, (key, name) in enumerate(ROWS):
    L += rule(i)
    L.append(f"{name} & " + " & ".join(nat(q[j][key], d) for j, _, d in J) + r" \\")
L += [r"\bottomrule", r"\end{tabular}"]
open(os.path.join(OUT, "tabA_e15q.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
