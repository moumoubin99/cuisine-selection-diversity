# ---- Table 2 / appendix: A3 re-selection vs top-16, per selector -> judge cell ----
# Two stacked panels so each fits the 5.5in text width: (a) the registered A3
# quantities under the pre-registered reader; (b) the same selected images read by
# the reader-free DINOv2 measure and the two sensitivity readers (post hoc).
def a3_table(sc, fname):
    judge = SC_NAME[[s for s in SCORERS if s != sc][0]]
    ra, rb = [], []
    for gi, g in enumerate(GENS):
        a = load("real", g)["a3__" + sc]
        claims = load("real", g)["claims__" + sc]["A3"]
        if gi:
            ra.append("\\midrule")
            rb.append("\\midrule")
        for fi, fam in enumerate(FAMS):
            ch = a["chosen_on_tuning"][fam]
            vt = ch["vs_topk"]
            key = f"{fam}|{ch['param']}"
            lead = [GEN_NAME[g] if fi == 0 else "",
                    f"{FAM_TEX[fam]} ({PARAM_TEX[fam].format(ch['param'])})"]
            q = load("real", g)["a3__" + sc]["curves_vs_topk"][key]["delta"]
            ra.append(" & ".join(lead + [
                f"${ch['evaluation']['gain_judge']['mean']:.3f}$ / ${vt['topk_judge_gain']['mean']:.3f}$",
                vci(100 * vt["judge_gain_retained"], [100 * c for c in vt["judge_gain_retained_ci"]],
                    f=ident, sign=False),
                vci(vt["raw_gain_judge"]["mean"], vt["raw_gain_judge"]["ci"], f=ident, nd=3),
                vci(q["mean"], q["ci"]),
                f"${claims['p_holm']:.3f}$" if fam == claims["family"] else "--"]) + " \\\\")
            cells = lead + [vci(vt["emb_delta"]["mean"], vt["emb_delta"]["ci"])]
            for rd, rdir in READERS[1:]:
                d = load(rdir, g)["a3__" + sc]["curves_vs_topk"][key]["delta"]
                cells.append(vci(d["mean"], d["ci"]))
            rb.append(" & ".join(cells) + " \\\\")
    write(fname, "\n".join([
        "\\begin{tabular}{llccccc}", "\\toprule",
        "\\multicolumn{7}{l}{\\textit{(a) Registered A3 quantities, pre-registered reader (Qwen2.5-VL)}} \\\\",
        f" & & {judge} gain, SD & Retention, & Raw {judge} & Dish-label & A3 \\\\",
        "Gen. & Method & sel.\\ / top-16 & \\% of top-16 & $\\Delta$ vs top-16 & vs top-16, \\% & Holm $p$ \\\\",
        "\\midrule", *ra, "\\bottomrule", "\\end{tabular}", "", "\\vspace{4pt}", "",
        "\\begin{tabular}{llccc}", "\\toprule",
        "\\multicolumn{5}{l}{\\textit{(b) Same selected images: DINOv2 (registered secondary) and sensitivity readers (post hoc)}} \\\\",
        " & & DINOv2 Vendi & \\multicolumn{2}{c}{Dish-label Vendi vs top-16, \\%} \\\\",
        "\\cmidrule(lr){4-5}",
        "Gen. & Method & vs top-16, \\% & " + " & ".join(RD_NAME[r] for r, _ in READERS[1:]) + " \\\\",
        "\\midrule", *rb, "\\bottomrule", "\\end{tabular}", ""]))


