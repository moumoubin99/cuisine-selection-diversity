def n(x, nd=1, sign=True):
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return "$" + s.replace("-", "-") + "$"


def vci(v, ci, f=pct, nd=1, sign=True):
    lo, hi = f(ci[0]), f(ci[1])
    return (f"{n(f(v), nd, sign)}\\,{{\\scriptsize$[{lo:+.{nd}f}, {hi:+.{nd}f}]$}}"
            if sign else
            f"{n(f(v), nd, False)}\\,{{\\scriptsize$[{lo:.{nd}f}, {hi:.{nd}f}]$}}")


def ident(x):
    return x


def write(name, body):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by paper/figures/scripts/make_tables.py -- do not edit\n" + body)
    print("wrote", name)


